"""Inventory books and Excel exports.

Every figure here is derived from the ledger, never from a second running total.
That is what makes the workbook reconcilable: if the closing balance in the book
disagrees with the item, the ledger is right and the item is the bug.

Each workbook opens with a provenance sheet - who generated it, when, over what
range, with which filters - so a spreadsheet found six months later can still be
explained.
"""

from __future__ import annotations

import io
import uuid
from collections import defaultdict
from datetime import UTC, date, datetime
from typing import Any

from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.db.models.inventory import InventoryBatch, InventoryItem, InventoryMovement, MovementType
from app.db.models.procurement import PurchaseOrder, PurchaseOrderLine, Vendor

# Paypal palette, so an exported book looks like the product it came from.
_NAVY = "FF002E6E"
_CYAN = "FF00BAF2"
_INK = "FF0B1B33"
_MUTED = "FF5B6B82"
_BAND = "FFF4F7FB"

_HEADER_FILL = PatternFill("solid", fgColor=_NAVY)
_HEADER_FONT = Font(color="FFFFFFFF", bold=True, size=10)
_TITLE_FONT = Font(color=_INK, bold=True, size=14)
_LABEL_FONT = Font(color=_MUTED, size=9)
_THIN = Side(style="thin", color="FFE7ECF3")
_BORDER = Border(left=_THIN, right=_THIN, top=_THIN, bottom=_THIN)

#: Movements grouped into the columns a stock book actually has.
_BOOK_COLUMNS: dict[str, tuple[str, ...]] = {
    "Purchases": (MovementType.PURCHASE_RECEIPT, MovementType.RESTOCK),
    "Sales": (MovementType.SALE, MovementType.CONSUMPTION),
    "Returns": (MovementType.CUSTOMER_RETURN,),
    "Transfers": (MovementType.TRANSFER_IN, MovementType.TRANSFER_OUT),
    "Adjustments": (MovementType.ADJUSTMENT,),
    "Wastage": (MovementType.WASTAGE, MovementType.DAMAGE),
    "Expired": (MovementType.EXPIRY,),
}


def _sheet(wb: Workbook, title: str, headers: list[str]) -> Any:
    ws = wb.create_sheet(title[:31])
    ws.append(headers)
    for index, _ in enumerate(headers, start=1):
        cell = ws.cell(row=1, column=index)
        cell.fill = _HEADER_FILL
        cell.font = _HEADER_FONT
        cell.alignment = Alignment(horizontal="left", vertical="center")
        cell.border = _BORDER
    ws.freeze_panes = "A2"
    return ws


def _autosize(ws: Any, maximum: int = 46) -> None:
    widths: dict[int, int] = defaultdict(int)
    for row in ws.iter_rows():
        for cell in row:
            if cell.value is not None:
                widths[cell.column] = max(widths[cell.column], len(str(cell.value)))
    for column, width in widths.items():
        ws.column_dimensions[get_column_letter(column)].width = min(width + 3, maximum)


def _provenance(
    wb: Workbook, *, merchant: str, generated_by: str, report: str, filters: dict[str, Any]
) -> None:
    """The first sheet of every workbook. Answers "where did this come from?"."""
    ws = wb.active
    ws.title = "About"
    ws["A1"] = "PayPilot"
    ws["A1"].font = Font(color=_CYAN, bold=True, size=10)
    ws["A2"] = report
    ws["A2"].font = _TITLE_FONT

    rows = [
        ("Merchant", merchant),
        ("Generated at", datetime.now(tz=UTC).strftime("%Y-%m-%d %H:%M UTC")),
        ("Generated by", generated_by),
        ("Source", "Inventory ledger (append-only)"),
        *[(key.replace("_", " ").title(), str(value)) for key, value in filters.items()],
    ]
    for offset, (label, value) in enumerate(rows, start=4):
        ws.cell(row=offset, column=1, value=label).font = _LABEL_FONT
        ws.cell(row=offset, column=2, value=value).font = Font(color=_INK, size=10)

    ws.cell(
        row=len(rows) + 5,
        column=1,
        value=(
            "Every quantity is derived from the stock movement ledger. The ledger is "
            "append-only: corrections appear as new movements, never as edits."
        ),
    ).font = _LABEL_FONT
    _autosize(ws)


class InventoryReports:
    def __init__(self, session: AsyncSession, merchant_id: uuid.UUID) -> None:
        self.session = session
        self.merchant_id = merchant_id

    # ------------------------------------------------------------------ book
    async def stock_book(
        self, *, start: date, end: date
    ) -> list[dict[str, Any]]:
        """Opening, movement columns and closing per SKU, straight from the ledger.

        Opening stock is reconstructed by rewinding the earliest in-range movement
        rather than trusting a stored snapshot - the ledger is the only source.
        """
        items = list(
            (
                await self.session.execute(
                    select(InventoryItem)
                    .where(InventoryItem.merchant_id == self.merchant_id)
                    .order_by(InventoryItem.sku)
                )
            ).scalars().all()
        )
        rows: list[dict[str, Any]] = []

        for item in items:
            movements = list(
                (
                    await self.session.execute(
                        select(InventoryMovement)
                        .where(
                            InventoryMovement.inventory_item_id == item.id,
                            InventoryMovement.created_at >= datetime.combine(
                                start, datetime.min.time(), tzinfo=UTC
                            ),
                            InventoryMovement.created_at <= datetime.combine(
                                end, datetime.max.time(), tzinfo=UTC
                            ),
                        )
                        .order_by(InventoryMovement.created_at)
                    )
                ).scalars().all()
            )

            buckets = dict.fromkeys(_BOOK_COLUMNS, 0.0)
            for movement in movements:
                for column, types in _BOOK_COLUMNS.items():
                    if movement.movement_type in types:
                        buckets[column] += float(movement.quantity)

            if movements:
                opening = float(movements[0].balance_before)
                closing = float(movements[-1].balance_after)
            else:
                opening = closing = float(item.quantity_on_hand)

            unit_cost = float(item.unit_cost or 0)
            rows.append(
                {
                    "sku": item.sku,
                    "product": item.product_name,
                    "opening": opening,
                    **{key.lower(): round(value, 2) for key, value in buckets.items()},
                    "closing": closing,
                    "unit_cost": unit_cost,
                    "value": round(closing * unit_cost, 2),
                    "status": item.status,
                    "movements": len(movements),
                }
            )
        return rows

    # ------------------------------------------------------------------ export
    async def workbook(
        self,
        *,
        merchant_name: str,
        generated_by: str,
        start: date,
        end: date,
        include_value: bool,
    ) -> bytes:
        """The full inventory book, as a multi-sheet workbook.

        ``include_value`` is driven by the caller's permission - a user who may
        not see valuation gets a workbook without cost columns rather than a
        hidden column they could unhide.
        """
        wb = Workbook()
        _provenance(
            wb,
            merchant=merchant_name,
            generated_by=generated_by,
            report="Inventory Book",
            filters={
                "date_range": f"{start} to {end}",
                "includes_valuation": "yes" if include_value else "no (permission)",
            },
        )

        # ---- Summary
        book = await self.stock_book(start=start, end=end)
        headers = [
            "SKU", "Product", "Opening", "Purchases", "Sales", "Returns",
            "Transfers", "Adjustments", "Wastage", "Expired", "Closing", "Status",
        ]
        if include_value:
            headers += ["Unit Cost", "Stock Value"]
        ws = _sheet(wb, "Inventory Summary", headers)
        for row in book:
            values = [
                row["sku"], row["product"], row["opening"], row["purchases"],
                row["sales"], row["returns"], row["transfers"], row["adjustments"],
                row["wastage"], row["expired"], row["closing"], row["status"],
            ]
            if include_value:
                values += [row["unit_cost"], row["value"]]
            ws.append(values)

        if book:
            total_row = ws.max_row + 1
            ws.cell(row=total_row, column=1, value="TOTAL").font = Font(bold=True)
            # A live formula, so the reader can re-sort or filter and still trust it.
            for column in range(3, 12):
                letter = get_column_letter(column)
                ws.cell(
                    row=total_row,
                    column=column,
                    value=f"=SUM({letter}2:{letter}{total_row - 1})",
                ).font = Font(bold=True)
            if include_value:
                letter = get_column_letter(len(headers))
                ws.cell(
                    row=total_row,
                    column=len(headers),
                    value=f"=SUM({letter}2:{letter}{total_row - 1})",
                ).font = Font(bold=True)
        _autosize(ws)

        # ---- Ledger
        movements = list(
            (
                await self.session.execute(
                    select(InventoryMovement)
                    .where(InventoryMovement.merchant_id == self.merchant_id)
                    .order_by(InventoryMovement.created_at.desc())
                    .limit(5000)
                )
            ).scalars().all()
        )
        ledger_headers = [
            "When", "Movement", "Quantity", "Balance Before", "Balance After",
            "Reference", "Source", "Actor", "Correlation ID", "Note",
        ]
        if include_value:
            ledger_headers.insert(5, "Unit Cost")
            ledger_headers.insert(6, "Total Value")
        ws = _sheet(wb, "Stock Ledger", ledger_headers)
        for m in movements:
            row = [
                m.created_at.strftime("%Y-%m-%d %H:%M") if m.created_at else "",
                m.movement_type,
                float(m.quantity),
                float(m.balance_before),
                float(m.balance_after),
            ]
            if include_value:
                row += [float(m.unit_cost or 0), float(m.total_value or 0)]
            row += [
                f"{m.reference_type}:{m.reference_id}" if m.reference_type else "",
                m.source,
                m.actor_type,
                m.correlation_id,
                m.note,
            ]
            ws.append(row)
        _autosize(ws)

        # ---- Purchase orders
        orders = list(
            (
                await self.session.execute(
                    select(PurchaseOrder)
                    .where(PurchaseOrder.merchant_id == self.merchant_id)
                    .order_by(PurchaseOrder.created_at.desc())
                )
            ).scalars().all()
        )
        ws = _sheet(
            wb,
            "Purchase Orders",
            ["Reference", "Status", "Vendor", "Source", "Total", "Approval",
             "Raised", "Expected", "Dry Run", "Correlation ID"],
        )
        for o in orders:
            ws.append([
                o.reference,
                o.status,
                o.vendor.name if o.vendor else "",
                o.source,
                float(o.total_value or 0),
                "required" if o.requires_approval else "automatic",
                o.created_at.strftime("%Y-%m-%d %H:%M") if o.created_at else "",
                str(o.expected_at) if o.expected_at else "",
                "yes" if o.is_dry_run else "no",
                o.correlation_id or "",
            ])
        _autosize(ws)

        # ---- PO lines, so receiving can be reconciled line by line
        lines = list(
            (
                await self.session.execute(
                    select(PurchaseOrderLine)
                    .where(PurchaseOrderLine.merchant_id == self.merchant_id)
                    .order_by(PurchaseOrderLine.created_at.desc())
                )
            ).scalars().all()
        )
        ws = _sheet(
            wb,
            "PO Lines",
            ["SKU", "Product", "Ordered", "Received", "Outstanding", "Unit Price", "Line Total"],
        )
        for line in lines:
            ws.append([
                line.sku,
                line.product_name,
                float(line.quantity_ordered),
                float(line.quantity_received),
                line.quantity_outstanding,
                float(line.unit_price or 0),
                float(line.line_total or 0),
            ])
        _autosize(ws)

        # ---- Aging
        batches = list(
            (
                await self.session.execute(
                    select(InventoryBatch)
                    .where(InventoryBatch.merchant_id == self.merchant_id)
                    .order_by(InventoryBatch.expiry_date.nulls_last())
                )
            ).scalars().all()
        )
        ws = _sheet(
            wb,
            "Aging",
            ["Batch", "Quantity", "Status", "Received", "Expiry", "Days Left", "Unit Cost"],
        )
        today = date.today()
        for b in batches:
            ws.append([
                b.batch_code,
                float(b.quantity),
                b.status,
                b.received_at.strftime("%Y-%m-%d") if b.received_at else "",
                str(b.expiry_date) if b.expiry_date else "",
                (b.expiry_date - today).days if b.expiry_date else "",
                float(b.unit_cost or 0),
            ])
        _autosize(ws)

        # ---- Vendors
        vendors = list(
            (
                await self.session.execute(
                    select(Vendor)
                    .where(Vendor.merchant_id == self.merchant_id)
                    .order_by(Vendor.name)
                )
            ).scalars().all()
        )
        ws = _sheet(
            wb,
            "Vendors",
            ["Vendor", "Contact", "Email", "Ordering", "Lead Days", "Active", "Items Supplied"],
        )
        for v in vendors:
            ws.append([
                v.name, v.contact_name, v.email, v.ordering_method,
                float(v.lead_time_days), "yes" if v.is_active else "no",
                len(v.supplies or []),
            ])
        _autosize(ws)

        for sheet in wb.worksheets:
            if sheet.max_row > 1 and sheet.title != "About":
                sheet.auto_filter.ref = sheet.dimensions

        buffer = io.BytesIO()
        wb.save(buffer)
        return buffer.getvalue()
