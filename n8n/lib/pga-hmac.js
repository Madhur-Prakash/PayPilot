// HMAC-SHA256 and canonical JSON, with no dependencies at all.
//
// n8n's Code node runs in a sandbox that refuses `require('crypto')`, and the
// flag that would allow it cannot be set on n8n Cloud. Rather than tie the
// deployment to one hosting choice, the ~90 lines of SHA-256 live here. They are
// inlined verbatim into every Code node by n8n/build_workflows.py.
//
// `canon()` must stay byte-identical to canonical_json() in
// backend/app/services/inventory/events.py - that agreement is what makes the
// signature verifiable on both sides of the wire.

